# 「長いと薄まる」という B+D2 の知見と衝突した。
# 流動性の効果を長さの効果から切り分けるため、現行に寄せる
STANCE_COUNT = 2
BAN_COUNT = 3


def build_fluid(rng, stance_count=STANCE_COUNT, ban_count=BAN_COUNT):
    """生成ごとに姿勢と禁止語を選び直したシステムプロンプトを組む。
    rng を渡すのは、どの組み合わせが出たかを記録・再現できるようにするため"""
    stance = rng.sample(STANCE_CLAUSES, stance_count)
    banned = rng.sample(RUT_WORDS, ban_count)
    parts = [CORE_CLAUSES[0], CORE_CLAUSES[1]]
    parts.extend(stance)
    parts.append(
        "・".join(banned) + "といった言葉と、その常套的な連想には頼らない。")
    parts.extend(CORE_CLAUSES[2:])
    return "".join(parts), stance, banned


def build_prefix_text(tokenizer, system_prompt, user_prompt):
    """システムプロンプトを直接渡して前置きを組む。流動版で使う"""
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]
    return tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True) + PREFILL


def build_prefix(tokenizer, condition, user_prompt):
    """条件名とお題から、生成の前置き(チャットテンプレート+書き出し)を作る"""
    messages = [
        {"role": "system", "content": SYSTEM_PROMPTS[condition]},
        {"role": "user", "content": user_prompt},
    ]
    return tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True) + PREFILL
