def rubric_text(severity):
    """ルーブリックの本文を組む"""
    levels = LEVELS[severity]
    lines = [f"評価は5段階。{SEVERITY_NOTE[severity]}", ""]
    for number, axis in enumerate(AXES, 1):
        lines.append(f"### {number}. {axis}")
        for score, text in enumerate(levels[axis], 1):
            lines.append(f"  {score}: {text}")
        lines.append("")
    return "\n".join(lines)


def build_score_prompt(severity, title="", note=""):
    """採点モードの指示を組む。本文は呼び手が付ける"""
    head = [SEVERITY_ROLE[severity],
            "以下の作品を7つの観点から評価する。", ""]
    head.append("守ること:")
    head.extend(f"- {rule}" for rule in SEVERITY_RULES[severity])
    head.append("- 指摘には必ず段落番号 [12] を添える。"
                "番号は渡された本文のものだけを使う。")
    head.append("- 本文に無い要素について述べない。")
    head.append("")
    head.append(rubric_text(severity))
    head.append(OUTPUT_FORMAT[severity])
    return "\n".join(head)
